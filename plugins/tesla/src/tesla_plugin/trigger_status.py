"""The same operational summary for the owner panel and MCP callers."""
from collections import Counter


def operational_summary(items):
    """Count every selector in the supplied scope, including rule selectors."""
    return dict(Counter(item["operational"]["status"] for item in items))


def operational_status(item, *, connected, membership_fresh, access, subscribed, selected_events):
    def state(status, label, reason, next_step):
        return {"status": status, "label": label, "reason": reason, "next_step": next_step,
                "basis": "last_stored_evidence", "notification_proven": False}

    if not item["enabled"]:
        return state("disabled", 'Not selected', "not_selected", 'Select it here or in chat. Collection remains unchanged.')
    if not connected:
        return state("blocked", 'Account connection required', "tesla_disconnected", "Ricollega l’account Tesla.")
    ready = item["readiness"]["status"]
    if ready == "permission_required":
        return state("blocked", 'Permission required', ready, "Check the permissions granted to the Tesla app.")
    if item["id"].startswith("rule:"):
        destinations = set(item["event_kinds"]) & selected_events
        if not destinations:
            return state("blocked", 'No alerts selected', "event_not_selected", 'Select at least one event generated by this rule.')
        covered = bool(destinations & subscribed)
    else:
        covered = item["subscribed"]
    if not covered:
        return state("blocked", 'Event connection required', "native_subscription_missing", 'Connect or renew event delivery in the ChatGPT host while preserving saved selections.')
    if ready == "rule_required":
        return state("blocked", 'Condition requires configuration', ready, 'Configure or enable a rule for this event.')
    if ready == "collection_unverified":
        return state("blocked", 'Collection needs verification', ready, 'Request verification of the configuration already on Tesla; do not apply a new profile just to verify it.')
    if ready.startswith("collection_"):
        return state("blocked", 'Collection needs verification', ready, 'Open the required-data proposal and review its cost before applying it.')
    if ready.startswith("data_"):
        return state("waiting_for_data", 'Waiting for valid data', ready, 'Fresh, consistent observations are required. No automatic wake commands.')
    if ready == "timing_warning":
        return state("needs_review", 'Timing needs review', ready, 'Compare collection intervals with rule requirements and the cost of the change.')
    if not membership_fresh:
        if access["automatic"] and not access["blocked_reason"]:
            return state("waiting_for_access", 'Check at delivery', "membership_check_stale", 'Access will be checked automatically when a valid event is pending delivery.')
        return state("blocked", 'Access needs verification', access["blocked_reason"] or "membership_check_stale", 'Verify vehicle membership or review the additional access check.')
    return state("ready", "Ready at the last check", "requirements_met", 'No action required. Notification also depends on host processing.')
